void playMelodySafe() {
    const int sampleRate = 44100;
    std::vector<int16_t> pcmData;

    int total_notes = sizeof(melody) / sizeof(melody[0]);

    for (int i = 0; i < total_notes; ++i) {
        int freq = melody[i][0];
        int dur_ms = melody[i][1];

        if (freq > 0) {
            while (freq < 140) {
                freq *= 2;
            }
        }

        int numSamples = (sampleRate * dur_ms) / 1000;
        for (int s = 0; s < numSamples; ++s) {
            if (freq == 0) {
                pcmData.push_back(0);
            }
            else {
                double t = static_cast<double>(s) / sampleRate;
                double wave = std::sin(2.0 * 3.1415926535 * freq * t);
                int16_t sample = (wave >= 0.0) ? 8000 : -8000;
                pcmData.push_back(sample);
            }
        }
    }

    uint32_t dataSize = static_cast<uint32_t>(pcmData.size() * sizeof(int16_t));
    uint32_t chunkSize = 36 + dataSize;
    std::vector<uint8_t> wavBuffer(44 + dataSize);

    auto write32 = [&](int offset, uint32_t val) {
        wavBuffer[offset] = val & 0xFF;
        wavBuffer[offset + 1] = (val >> 8) & 0xFF;
        wavBuffer[offset + 2] = (val >> 16) & 0xFF;
        wavBuffer[offset + 3] = (val >> 24) & 0xFF;
        };
    auto write16 = [&](int offset, uint16_t val) {
        wavBuffer[offset] = val & 0xFF;
        wavBuffer[offset + 1] = (val >> 8) & 0xFF;
        };

    // Записуємо правильні зсуви заголовка WAV
    std::memcpy(&wavBuffer[0], "RIFF", 4);
    write32(4, chunkSize);
    std::memcpy(&wavBuffer[8], "WAVEfmt ", 8);
    write32(16, 16);
    write16(20, 1);
    write16(22, 1);
    write32(24, sampleRate);
    write32(28, sampleRate * 2);
    write16(32, 2);
    write16(34, 16);
    std::memcpy(&wavBuffer[36], "data", 4);
    write32(40, dataSize);

    // Копіюємо звук починаючи з 44-го байта
    std::memcpy(&wavBuffer[44], pcmData.data(), dataSize);

    // Зберігаємо у тимчасовий файл
    const char* tempFile = "temp_melody.wav";
    std::ofstream out(tempFile, std::ios::binary);
    out.write(reinterpret_cast<const char*>(wavBuffer.data()), wavBuffer.size());
    out.close();

    // Відтворюємо через MCI (працює в окремому потоці Windows без переповнення стека)
    mciSendStringA("open \"temp_melody.wav\" type waveaudio alias my_melody", NULL, 0, NULL);
    mciSendStringA("play my_melody wait", NULL, 0, NULL);
    mciSendStringA("close my_melody", NULL, 0, NULL);

    std::remove(tempFile);
}

int main() {
    playMelodySafe();
    return 0;
}